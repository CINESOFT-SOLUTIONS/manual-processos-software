#!/bin/bash
set -e

ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
TARGET_FILE="$ROOT_DIR/manual-processos-software.md"

# Paleta CLI Vitest/pnpm (ativo por padrão, respeita NO_COLOR)
if [ -z "$NO_COLOR" ]; then
    BG_MAGENTA='\033[45;37;1m'
    BG_GREEN='\033[42;30;1m'
    CYAN='\033[36m'
    GREEN='\033[32m'
    DIM='\033[2m'
    BOLD='\033[1m'
    RESET='\033[0m'
else
    BG_MAGENTA=''
    BG_GREEN=''
    CYAN=''
    GREEN=''
    DIM=''
    BOLD=''
    RESET=''
fi

printf " ${BG_MAGENTA} ASSEMBLE ${RESET} ${CYAN}content/${RESET} -> ${BOLD}manual-processos-software.md${RESET}\n"

# Cabeçalho com aviso de arquivo gerado
cat << 'HEADER' > "$TARGET_FILE"
<!-- ===================================================================== -->
<!-- NOTICE: AUTO-GENERATED FILE FROM content/                             -->
<!-- DO NOT EDIT THIS FILE DIRECTLY. EDIT THE MODULES IN content/          -->
<!-- TO REBUILD: run ./scripts/compilar.sh or ./scripts/montar-manual.sh   -->
<!-- ===================================================================== -->

HEADER

FIRST=1
for file in "$ROOT_DIR"/content/[0-9][0-9]-*.md; do
    if [ -f "$file" ]; then
        filename=$(basename "$file")
        printf "  ${DIM}+${RESET} %s\n" "content/$filename"
        if [ $FIRST -eq 0 ]; then
            printf "\n\n" >> "$TARGET_FILE"
        fi
        cat "$file" >> "$TARGET_FILE"
        FIRST=0
    fi
done

LINES=$(wc -l < "$TARGET_FILE" | tr -d ' ')
printf "  ${GREEN}✓${RESET} ${BOLD}manual-processos-software.md${RESET} ${DIM}(%s lines)${RESET}\n" "$LINES"
